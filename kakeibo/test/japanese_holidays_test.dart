import 'package:flutter_test/flutter_test.dart';
import 'package:kakeibo/core/utils/japanese_holidays.dart';

Map<String, String> _year(int y) => {
      for (final MapEntry(key: d, value: name) in (japaneseHolidays(y).entries.toList()..sort((a, b) => a.key.compareTo(b.key))))
        '${d.month}/${d.day}': name,
    };

void main() {
  test('2026年（9/22 の国民の休日、5/6 の振替休日を含む）', () {
    expect(_year(2026), {
      '1/1': '元日', '1/12': '成人の日', '2/11': '建国記念の日', '2/23': '天皇誕生日', '3/20': '春分の日',
      '4/29': '昭和の日', '5/3': '憲法記念日', '5/4': 'みどりの日', '5/5': 'こどもの日', '5/6': '振替休日',
      '7/20': '海の日', '8/11': '山の日', '9/21': '敬老の日', '9/22': '国民の休日', '9/23': '秋分の日',
      '10/12': 'スポーツの日', '11/3': '文化の日', '11/23': '勤労感謝の日',
    });
  });

  test('2025年（振替休日が4回）', () {
    expect(_year(2025), {
      '1/1': '元日', '1/13': '成人の日', '2/11': '建国記念の日', '2/23': '天皇誕生日', '2/24': '振替休日',
      '3/20': '春分の日', '4/29': '昭和の日', '5/3': '憲法記念日', '5/4': 'みどりの日', '5/5': 'こどもの日',
      '5/6': '振替休日', '7/21': '海の日', '8/11': '山の日', '9/15': '敬老の日', '9/23': '秋分の日',
      '10/13': 'スポーツの日', '11/3': '文化の日', '11/23': '勤労感謝の日', '11/24': '振替休日',
    });
  });

  test('2024年', () {
    expect(_year(2024), {
      '1/1': '元日', '1/8': '成人の日', '2/11': '建国記念の日', '2/12': '振替休日', '2/23': '天皇誕生日',
      '3/20': '春分の日', '4/29': '昭和の日', '5/3': '憲法記念日', '5/4': 'みどりの日', '5/5': 'こどもの日',
      '5/6': '振替休日', '7/15': '海の日', '8/11': '山の日', '8/12': '振替休日', '9/16': '敬老の日',
      '9/22': '秋分の日', '9/23': '振替休日', '10/14': 'スポーツの日', '11/3': '文化の日', '11/4': '振替休日',
      '11/23': '勤労感謝の日',
    });
  });

  test('2019年の即位に伴う休日と、天皇誕生日が無いこと', () {
    final y = _year(2019);
    expect(y['4/30'], '国民の休日');
    expect(y['5/1'], '天皇の即位の日');
    expect(y['5/2'], '国民の休日');
    expect(y['5/6'], '振替休日');
    expect(y['10/22'], '即位礼正殿の儀の行われる日');
    expect(y.containsKey('12/23'), isFalse);
    expect(y.containsKey('2/23'), isFalse);
  });

  test('2020・2021年の東京五輪による移動', () {
    final y20 = _year(2020), y21 = _year(2021);
    expect([y20['7/23'], y20['7/24'], y20['8/10']], ['海の日', 'スポーツの日', '山の日']);
    expect(y20.values.where((n) => n == 'スポーツの日').length, 1); // 10月には無い
    expect([y21['7/22'], y21['7/23'], y21['8/8'], y21['8/9']], ['海の日', 'スポーツの日', '山の日', '振替休日']);
  });

  test('2015年のシルバーウィークと、2006年までの5/4', () {
    expect(_year(2015)['9/22'], '国民の休日');
    expect(_year(2006)['5/4'], '国民の休日');
    expect(_year(2006)['4/29'], 'みどりの日');
    expect(_year(2018)['12/23'], '天皇誕生日');
    expect(_year(2018)['12/24'], '振替休日');
  });

  test('japaneseHolidayName は時刻があっても日付で判定する', () {
    expect(japaneseHolidayName(DateTime(2026, 11, 3, 15, 30)), '文化の日');
    expect(japaneseHolidayName(DateTime(2026, 11, 4)), isNull);
  });
}
